import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import App from './App';
import { AuthProvider } from './context/AuthContext';
import { ThemeProvider } from './context/ThemeContext';
import { isAdminPinFailure } from './services/adminPinElevation';
import './styles.css';
const queryClient=new QueryClient({defaultOptions:{queries:{staleTime:30_000,retry:(failures,error)=>failures<1&&!isAdminPinFailure(error)}}});
createRoot(document.getElementById('root')!).render(<StrictMode><ThemeProvider><QueryClientProvider client={queryClient}><BrowserRouter><AuthProvider><App/></AuthProvider></BrowserRouter></QueryClientProvider></ThemeProvider></StrictMode>);
